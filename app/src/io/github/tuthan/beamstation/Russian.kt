    private fun patterns(english: String): String {
        // Notices are saved in the language in use when they were generated.
        val prefixes = arrayOf("Couldn't check " + Config.APP_NAME + ": ", "Couldn't turn on " + Config.APP_NAME + ": ",
            "Couldn't go back to the original: ", "Original mode, but I couldn't turn back on: ")
        for (p in prefixes) if (english.startsWith(p)) return text(p) + text(english.substring(p.length))
        val shelfPrefix = "OK adds or removes (up to "
        val shelfSuffix = "). ← → change the order."
        if (english.startsWith(shelfPrefix) && english.endsWith(shelfSuffix)) {
            val n = english.substring(shelfPrefix.length, english.length - shelfSuffix.length)
            return "OK — добавить или убрать (до " + n + "). ← → — изменить порядок."
        }
        val prefix = Config.APP_NAME + " is on: new home screen and screensaver, "
        if (english.startsWith(prefix) && english.endsWith(" apps turned off.")) {
            val n = english.substring(prefix.length, english.length - " apps turned off.".length)
            return Config.APP_NAME + " включён: новый главный экран и заставка; отключено приложений: " + n + "."
        }
        if (english.startsWith("On · ") && english.endsWith(" titles from the TV's apps, 3 new ones every hour.")) {
            val n = english.substring(5, english.length - " titles from the TV's apps, 3 new ones every hour.".length)
            return "Вкл. · Рекомендаций из приложений телевизора: " + n + "; 3 новых каждый час."
        }
        if (english.endsWith(" min ago")) return english.substring(0, english.length - 8) + " мин назад"
        if (english.endsWith(" h ago")) return english.substring(0, english.length - 6) + " ч назад"
        if (english.endsWith(" days ago")) {
            return try {
                count(english.substring(0, english.length - 9).toLong(), "день", "дня", "дней") + " назад"
            } catch (ignored: NumberFormatException) {
                english
            }
        }
        return english
    }
