    fun count(n: Long, one: String, few: String, many: String): String {
        val last = abs(n % 100)
        val word = if (last >= 11 && last <= 14) many
        else if (last % 10 == 1L) one else if (last % 10 >= 2 && last % 10 <= 4) few else many
        return n.toString() + " " + word
    }

